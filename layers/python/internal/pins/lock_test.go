package pins

import (
	"bytes"
	"strings"
	"testing"
)

func TestLockDeterministic(t *testing.T) {
	t.Parallel()
	pure := Locked{
		Name: "Six", Version: "1.17.0", Why: "pinned by upstream",
		Files: []File{{Name: "six-1.17.0-py2.py3-none-any.whl", SHA256: strings.Repeat("6", 64)}},
	}
	built := Locked{
		Name: "PyYAML", Version: "6.0.3", Why: "pinned by upstream", FromSource: true,
		Files: []File{{Name: "pyyaml-6.0.3.tar.gz", SHA256: strings.Repeat("9", 64)}},
	}
	cryptography := Locked{
		Name: "cryptography", Version: "50.0.2", Why: "pins.txt: upstream leaves it unpinned (>=3.0)", FromSource: true,
		Files: []File{{Name: "cryptography-50.0.2.tar.gz", SHA256: strings.Repeat("c", 64)}},
	}
	lock := func(pkgs ...Locked) string {
		var b bytes.Buffer
		if err := WriteLock(&b, Lock{Header: []string{"Generated by go run ./cmd/divbast-pins.", "Do not edit."}, Packages: pkgs}); err != nil {
			t.Fatal(err)
		}
		return b.String()
	}
	first, second := lock(pure, built, cryptography), lock(cryptography, pure, built)
	if first != second {
		t.Errorf("the same packages in another order gave another lock:\n%s\n---\n%s", first, second)
	}
	want := `# Generated by go run ./cmd/divbast-pins.
# Do not edit.
--no-binary cryptography,pyyaml

# pins.txt: upstream leaves it unpinned (>=3.0); built from source
cryptography==50.0.2 \
    --hash=sha256:` + strings.Repeat("c", 64) + `

# pinned by upstream; built from source
pyyaml==6.0.3 \
    --hash=sha256:` + strings.Repeat("9", 64) + `

# pinned by upstream
six==1.17.0 \
    --hash=sha256:` + strings.Repeat("6", 64) + `
`
	if first != want {
		t.Errorf("WriteLock() =\n%s\nwant\n%s", first, want)
	}
	// With nothing built from source, no --no-binary line
	if got := lock(pure); strings.Contains(got, "--no-binary") {
		t.Errorf("WriteLock() of pure wheels alone =\n%s\nwant no --no-binary line", got)
	}
	// A yanked release upstream pins says so, and why, beside its pin
	yanked := pure
	yanked.Yanked, yanked.YankedReason = true, "broken metadata"
	if got := lock(yanked); !strings.Contains(got, "\n# pinned by upstream; yanked on PyPI: broken metadata\nsix==1.17.0 \\\n") {
		t.Errorf("WriteLock() of a yanked release =\n%s\nwant its comment to say it is yanked, and why", got)
	}
	// The reason is the maintainer's text: it stays one comment line, so it
	// can never add a line pip would read
	yanked.YankedReason = "bad build\n--index-url https://elsewhere.example/simple\r\n"
	if got := lock(yanked); strings.Contains(got, "\n--index-url") || !strings.Contains(got, "# pinned by upstream; yanked on PyPI: bad build --index-url https://elsewhere.example/simple\nsix==") {
		t.Errorf("WriteLock() of a reason with line breaks =\n%s\nwant it on the comment's one line", got)
	}
	yanked.YankedReason = ""
	if got := lock(yanked); !strings.Contains(got, "\n# pinned by upstream; yanked on PyPI, with no reason given\nsix==1.17.0 \\\n") {
		t.Errorf("WriteLock() of a yanked release with no reason =\n%s\nwant its comment to say it is yanked", got)
	}
}
